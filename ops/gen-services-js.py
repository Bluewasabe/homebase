"""Emit custom/shared/services.js from inventory/ so the from-scratch front doors
render the same service list as every other variant.

Run:  python ops/gen-services-js.py
"""
import json
import pathlib

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
services = yaml.safe_load((ROOT / "inventory/services.yaml").read_text(encoding="utf-8"))
hosts = yaml.safe_load((ROOT / "inventory/hosts.yaml").read_text(encoding="utf-8"))
out = ("// generated by ops/gen-services-js.py from inventory/ — do not edit\n"
       f"window.HB_SERVICES = {json.dumps(services, ensure_ascii=False, indent=1)};\n"
       f"window.HB_HOSTS = {json.dumps(hosts, ensure_ascii=False, indent=1)};\n")
p = ROOT / "custom/shared/services.js"
p.parent.mkdir(parents=True, exist_ok=True)
p.write_text(out, encoding="utf-8", newline="\n")
print(p, len(services), "services", len(hosts), "hosts")
